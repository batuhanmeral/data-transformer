import { existsSync, globSync, readFileSync, writeFileSync } from "node:fs";
import { basename, relative, resolve, sep } from "node:path";
import { pathToFileURL } from "node:url";

const root = "src/operations";
const destination = `${root}/index.generated.ts`;
const operationFiles = globSync(`${root}/**/*.ts`)
  .filter((file) => {
    const name = basename(file);
    return !name.startsWith("_") && !name.endsWith(".test.ts") && name !== "index.generated.ts";
  })
  .sort();
const ids = new Map<string, string>();
const imports: string[] = [];
const names: string[] = [];

for (const [index, file] of operationFiles.entries()) {
  const { default: operation }: { default?: unknown } = await import(pathToFileURL(resolve(file)).href);
  if (
    !operation || typeof operation !== "object" ||
    !("id" in operation) || typeof operation.id !== "string" || operation.id.length === 0
  ) {
    throw new Error(`${file} must default-export an operation with an ID.`);
  }

  const first = ids.get(operation.id);
  if (first) throw new Error(`Duplicate operation ID "${operation.id}" in ${first} and ${file}.`);
  ids.set(operation.id, file);

  const name = `operation${index}`;
  const path = relative(root, file).split(sep).join("/").replace(/\.ts$/, "");
  imports.push(`import ${name} from ${JSON.stringify(`./${path}`)};`);
  names.push(name);
}

const source = [
  "// Generated by scripts/gen-operations.ts.",
  ...imports,
  "",
  `export const operations = [${names.join(", ")}] as const;`,
  "",
].join("\n");

if (!existsSync(destination) || readFileSync(destination, "utf8") !== source) {
  writeFileSync(destination, source);
}
